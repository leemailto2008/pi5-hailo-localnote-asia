def test_number_next_to_each_char(src, want):
    assert tt.prepare_source(src, "en") == want


@pytest.mark.parametrize("src", ["兩2萬5千元", "2萬5千零元", "2萬5千 十元", "两2萬5千", "2萬5千百元"])
def test_never_sends_20005_thousand(src):
    # N9：原本「2萬5」被萬後接數字的規則換成 20005，後面的「千」再乘一次 → 20,005,000
    vals = tt.number_values(tt.prepare_source(src, "en"))
    assert 20005000.0 not in vals and 20005.0 not in vals, vals


@pytest.mark.parametrize("src,want", [("預算2萬5千.", "預算25000."), ("2萬5千, 3萬", "25000, 30,000"), ("3萬52.", "30052."),
                                      ("1千2.5", "1千2.5"), ("3萬52,000", "3萬52,000"), ("2萬5,000", "2萬5,000")])
def test_sentence_punctuation_after_composite(src, want):
    # 句點／逗號後面不是數字時是標點，照換；後面接數字才是小數點／千分位
    assert tt.prepare_source(src, "en") == want
